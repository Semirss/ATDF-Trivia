export function isSupportedLanguage(value: string | null | undefined): value is AppLanguage {
  return supportedLanguages.some((language) => language.code === value);
}

export function normalizeLanguage(value: string | null | undefined): AppLanguage {
  return isSupportedLanguage(value) ? value : defaultLanguage;
}

function cleanText(value: unknown) {
  return typeof value === "string" ? value.trim() : "";
}

export function normalizeQuestionTranslations(value: unknown): Record<string, Partial<QuestionTranslation>> {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return {};
  }

  const translations: Record<string, Partial<QuestionTranslation>> = {};

  for (const [language, rawTranslation] of Object.entries(value)) {
    if (!rawTranslation || typeof rawTranslation !== "object" || Array.isArray(rawTranslation)) {
      continue;
    }

    const source = rawTranslation as Record<string, unknown>;
    const translation: Partial<QuestionTranslation> = {
      questionText: cleanText(source.questionText),
      optionA: cleanText(source.optionA),
      optionB: cleanText(source.optionB),
      optionC: cleanText(source.optionC),
      optionD: cleanText(source.optionD),
      explanation: cleanText(source.explanation)
    };
    const hasContent = Object.values(translation).some(Boolean);

    if (hasContent) {
      translations[language] = translation;
    }
  }

  return translations;
}

export function hasQuestionTranslation(values: { translations?: Record<string, Partial<QuestionTranslation>> }, language: string) {
  const translation = values.translations?.[language];
  return Boolean(translation && Object.values(translation).some((value) => value.trim().length > 0));
}

export function getLocalizedQuestion(question: Question, language: AppLanguage) {
  const translation = language === defaultLanguage ? undefined : question.translations?.[language];

  return {
    questionText: translation?.questionText?.trim() || question.questionText,
    optionA: translation?.optionA?.trim() || question.optionA,
    optionB: translation?.optionB?.trim() || question.optionB,
    optionC: translation?.optionC?.trim() || question.optionC,
    optionD: translation?.optionD?.trim() || question.optionD,
    explanation: translation?.explanation?.trim() || question.explanation || ""
  };
}
